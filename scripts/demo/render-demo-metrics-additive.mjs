/**
 * Renders docs/ux-reconstruction/demo-metrics-additive.sql: an additive, idempotent operator script that
 * inserts the canonical V3 Demo metric rows (metric_definitions + metric_observations, migration 0017)
 * into the currently ACTIVE hosted Demo generation. It is generated from the same fixtures the operator
 * plan uses, so ids and content are identical to what a fresh generation would receive.
 *
 * No network, no database. Usage (from the repository root):
 *   node --experimental-transform-types --disable-warning=MODULE_TYPELESS_PACKAGE_JSON \
 *     --import ./scripts/db-test/test-alias.mjs scripts/demo/render-demo-metrics-additive.mjs [--check]
 * --check fails if the committed SQL differs from a fresh render.
 */
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { canonicalDemoDataV3 } from '../../src/lib/demo/scenario-v3.ts';
import { demoProjectMetrics, demoPortfolioMetrics } from '../../src/lib/demo/metric-fixtures.ts';
import { demoId, DEMO_CANONICAL_VERSION, DEMO_CUTOFF, DEMO_ORGANIZATION_NAME } from '../../src/lib/demo/canonical.ts';

const OUTPUT = resolve('docs/ux-reconstruction/demo-metrics-additive.sql');
const TAP = 'tap-to-pay-merchant-onboarding';

/** The same composition as canonicalDemoDataV3, with symbolic ids the SQL resolves per workspace. */
function symbolicMetrics() {
  const v2 = key => `@id:v2:${key}`, v3 = key => `@id:v3:${key}`;
  return [
    ...demoProjectMetrics('@workspace', `@initiative:${TAP}`, v2(`${TAP}:evidence`), v2),
    ...demoPortfolioMetrics('@workspace', slug => `@initiative:${slug}`, v3),
  ];
}

/** Proves the symbolic composition equals the real dataset for a concrete workspace. */
function assertEquivalent(symbolic) {
  const identity = { workspaceId: 'e4000000-0000-4000-8000-000000000002', organizationId: 'e4000000-0000-4000-8000-000000000001', reviewerMemberId: 'e4000000-0000-4000-8000-000000000003', reviewerUserId: 'e4000000-0000-4000-8000-000000000004' };
  const demo = canonicalDemoDataV3(identity);
  const bySlug = new Map(demo.productStore.initiatives.map(i => [i.slug, i.id]));
  const resolveToken = value => {
    if (typeof value !== 'string') return value;
    if (value === '@workspace') return identity.workspaceId;
    if (value.startsWith('@initiative:')) return bySlug.get(value.slice(12));
    if (value.startsWith('@id:')) return demoId(identity.workspaceId, value.slice(4));
    return value;
  };
  const resolved = JSON.parse(JSON.stringify(symbolic), (_key, value) => resolveToken(value));
  assert.deepEqual(resolved, JSON.parse(JSON.stringify(demo.metrics)), 'Symbolic metric composition differs from canonicalDemoDataV3.');
}

const key = token => { assert.ok(typeof token === 'string' && token.startsWith('@id:'), 'Expected a symbolic id.'); return token.slice(4); };
function payload(metrics) {
  return metrics.map(m => ({
    key: key(m.id), initiative_slug: m.initiativeId.slice('@initiative:'.length), evidence_key: m.sourceEvidenceId ? key(m.sourceEvidenceId) : null,
    name: m.name, definition: m.definition, unit: m.unit, formula: m.formula, source_label: m.sourceLabel, period_grain: m.periodGrain, timezone: m.timezone,
    target_value: m.targetValue, target_comparator: m.targetComparator, target_owner_label: m.targetOwnerLabel, target_approved_at: m.targetApprovedAt, target_note: m.targetNote,
    origin: m.origin, revision: m.revision, updated_at: m.updatedAt,
    observations: m.observations.map(o => ({ key: key(o.id), period_start: o.periodStart, period_end: o.periodEnd, value: o.value, captured_at: o.capturedAt, evidence_key: o.sourceEvidenceId ? key(o.sourceEvidenceId) : null, note: o.note, origin: o.origin })),
  }));
}

export function renderAdditiveSql() {
  const metrics = symbolicMetrics();
  assertEquivalent(metrics);
  const rows = payload(metrics);
  const json = JSON.stringify(rows, null, 1);
  assert.ok(!json.includes('$payload$'));
  const observationCount = rows.reduce((n, m) => n + m.observations.length, 0);
  const sql = `-- Prodwise Demo · additive synthetic metrics for the ACTIVE hosted Demo generation.
-- GENERATED by scripts/demo/render-demo-metrics-additive.mjs from src/lib/demo/metric-fixtures.ts — do not edit by hand.
--
-- What it does: inserts ${rows.length} metric_definitions and ${observationCount} metric_observations (migration 0017 columns),
-- every row origin SYNTHETIC_DEMO, into the one ACTIVE registered Demo workspace. Ids are the same deterministic
-- demo ids the operator plan (scripts/demo/provision-hosted.mjs) gives a fresh generation, so a later reset agrees.
--
-- Safety:
--  * Additive only: no update, delete or truncate. One transaction; any refusal rolls everything back.
--  * Target resolution: demo_entry_config -> ACTIVE workspace -> ACTIVE organization named '${DEMO_ORGANIZATION_NAME}'
--    with a demo_scenarios row (${DEMO_CANONICAL_VERSION}, ${DEMO_CUTOFF}). Refuses unless that is exactly the one ACTIVE
--    registered Demo generation.
--  * Idempotent: a row that already exists with identical content is skipped; one that exists with different content
--    (or a period already recorded under another id) refuses the whole script.
--  * Initiatives are resolved by slug inside the Demo workspace (active, is_demo); a missing one refuses.
--  * Serialised with the Demo operator through the same advisory lock.
--
-- Review, then apply as the database owner (e.g. psql -v ON_ERROR_STOP=1 -f demo-metrics-additive.sql).
begin;
set local lock_timeout='10s';
set local statement_timeout='60s';
create function pg_temp.prodwise_demo_id(ws uuid,k text) returns uuid language sql immutable as $fn$
 select (substr(h,1,8)||'-'||substr(h,9,4)||'-4'||substr(h,14,3)||'-8'||substr(h,18,3)||'-'||substr(h,21,12))::uuid
 from (select encode(sha256(convert_to('prodwise-demo-only:'||ws::text||':'||k,'UTF8')),'hex') as h) x $fn$;
do $metrics$
declare
 payload constant jsonb := $payload$${json}$payload$::jsonb;
 ws uuid; org uuid; n integer; spec jsonb; ob jsonb; iid uuid; eid uuid; oeid uuid; mid uuid; obid uuid;
 d public.metric_definitions; o public.metric_observations;
 new_definitions integer := 0; same_definitions integer := 0; new_observations integer := 0; same_observations integer := 0;
begin
 perform pg_advisory_xact_lock(13142026);
 select count(*) into n from public.demo_entry_config;
 if n<>1 then raise exception 'DEMO_ENTRY_CONFIG_REQUIRED'; end if;
 select w.id,org_row.id into ws,org
 from public.demo_entry_config c
 join public.workspaces w on w.id=c.workspace_id and w.status='ACTIVE'
 join public.organizations org_row on org_row.id=w.organization_id and org_row.status='ACTIVE' and org_row.name=${literal(DEMO_ORGANIZATION_NAME)}
 join public.demo_scenarios s on s.workspace_id=w.id and s.organization_id=org_row.id
 where s.canonical_version=${literal(DEMO_CANONICAL_VERSION)} and s.scenario_at=${literal(DEMO_CUTOFF)}::timestamptz;
 if ws is null then raise exception 'DEMO_ENTRY_NOT_REGISTERED_ACTIVE_DEMO'; end if;
 select count(*) into n from public.demo_scenarios s
 join public.workspaces w on w.id=s.workspace_id and w.organization_id=s.organization_id and w.status='ACTIVE'
 join public.organizations org_row on org_row.id=s.organization_id and org_row.status='ACTIVE';
 if n<>1 then raise exception 'DEMO_ACTIVE_GENERATION_NOT_UNIQUE: % active registered Demo generations', n; end if;
 perform 1 from public.workspaces where id=ws for share;
 for spec in select value from jsonb_array_elements(payload) loop
  select count(*),min(i.id::text)::uuid into n,iid from public.initiatives i
   where i.workspace_id=ws and i.slug=spec->>'initiative_slug' and i.is_demo and i.archived_at is null;
  if n<>1 then raise exception 'DEMO_METRIC_INITIATIVE_MISSING: %', spec->>'initiative_slug'; end if;
  eid := case when spec->>'evidence_key' is null then null else pg_temp.prodwise_demo_id(ws,spec->>'evidence_key') end;
  if eid is not null and not exists(select 1 from public.evidence e where e.id=eid and e.workspace_id=ws and e.initiative_id=iid) then
   raise exception 'DEMO_METRIC_SOURCE_MISSING: %', spec->>'name'; end if;
  mid := pg_temp.prodwise_demo_id(ws,spec->>'key');
  select * into d from public.metric_definitions where id=mid;
  if found then
   if (d.workspace_id,d.organization_id,d.initiative_id,d.name,d.definition,d.unit,d.formula,d.source_label,d.source_evidence_id,d.period_grain,d.timezone,
       d.target_value,d.target_comparator,d.target_owner_label,d.target_approved_at,d.target_note,d.origin,d.revision,d.updated_at)
      is distinct from
      (ws,org,iid,spec->>'name',spec->>'definition',spec->>'unit',spec->>'formula',spec->>'source_label',eid,spec->>'period_grain',spec->>'timezone',
       (spec->>'target_value')::numeric,spec->>'target_comparator',spec->>'target_owner_label',(spec->>'target_approved_at')::timestamptz,spec->>'target_note',
       spec->>'origin',(spec->>'revision')::integer,(spec->>'updated_at')::timestamptz) then
    raise exception 'DEMO_METRIC_CONTENT_DIFFERS: definition %', spec->>'name';
   end if;
   same_definitions := same_definitions+1;
  else
   insert into public.metric_definitions(id,organization_id,workspace_id,initiative_id,name,definition,unit,formula,source_label,source_evidence_id,period_grain,timezone,
    target_value,target_comparator,target_owner_label,target_approved_at,target_note,origin,revision,updated_at)
   values(mid,org,ws,iid,spec->>'name',spec->>'definition',spec->>'unit',spec->>'formula',spec->>'source_label',eid,spec->>'period_grain',spec->>'timezone',
    (spec->>'target_value')::numeric,spec->>'target_comparator',spec->>'target_owner_label',(spec->>'target_approved_at')::timestamptz,spec->>'target_note',
    spec->>'origin',(spec->>'revision')::integer,(spec->>'updated_at')::timestamptz);
   new_definitions := new_definitions+1;
  end if;
  for ob in select value from jsonb_array_elements(spec->'observations') loop
   obid := pg_temp.prodwise_demo_id(ws,ob->>'key');
   oeid := case when ob->>'evidence_key' is null then null else pg_temp.prodwise_demo_id(ws,ob->>'evidence_key') end;
   if exists(select 1 from public.metric_observations x where x.metric_id=mid and x.period_start=(ob->>'period_start')::date and x.period_end=(ob->>'period_end')::date and x.id<>obid) then
    raise exception 'DEMO_METRIC_CONTENT_DIFFERS: % period % recorded under another id', spec->>'name', ob->>'period_start';
   end if;
   select * into o from public.metric_observations where id=obid;
   if found then
    if (o.metric_id,o.workspace_id,o.period_start,o.period_end,o.value,o.captured_at,o.source_evidence_id,o.note,o.origin)
       is distinct from
       (mid,ws,(ob->>'period_start')::date,(ob->>'period_end')::date,(ob->>'value')::numeric,(ob->>'captured_at')::timestamptz,oeid,ob->>'note',ob->>'origin') then
     raise exception 'DEMO_METRIC_CONTENT_DIFFERS: % period %', spec->>'name', ob->>'period_start';
    end if;
    same_observations := same_observations+1;
   else
    insert into public.metric_observations(id,metric_id,workspace_id,period_start,period_end,value,captured_at,source_evidence_id,note,origin)
    values(obid,mid,ws,(ob->>'period_start')::date,(ob->>'period_end')::date,(ob->>'value')::numeric,(ob->>'captured_at')::timestamptz,oeid,ob->>'note',ob->>'origin');
    new_observations := new_observations+1;
   end if;
  end loop;
 end loop;
 raise notice 'DEMO_METRICS_ADDITIVE workspace=% definitions inserted=% unchanged=% observations inserted=% unchanged=%',ws,new_definitions,same_definitions,new_observations,same_observations;
end $metrics$;
commit;
`;
  assert.ok(!/\b(delete|truncate|drop\s+table|update\s+public)\b/i.test(sql.replace(json, '').replace(/^--.*$/gm, '')), 'The additive script must not remove or rewrite rows.');
  return { sql, definitions: rows.length, observations: observationCount };
}
function literal(value) { return "'" + String(value).replaceAll("'", "''") + "'"; }

if (import.meta.url === new URL(`file://${resolve(process.argv[1] ?? '')}`).href) {
  const { sql, definitions, observations } = renderAdditiveSql();
  if (process.argv.includes('--check')) {
    assert.equal(readFileSync(OUTPUT, 'utf8'), sql, 'demo-metrics-additive.sql is stale; re-render it.');
    console.log(JSON.stringify({ status: 'PASS', check: true, definitions, observations }));
  } else {
    writeFileSync(OUTPUT, sql);
    console.log(JSON.stringify({ status: 'WRITTEN', path: 'docs/ux-reconstruction/demo-metrics-additive.sql', definitions, observations }));
  }
}
